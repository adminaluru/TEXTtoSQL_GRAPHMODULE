"""Versioned Golden Data fixtures for the integration tests (action A1.3).

    python -m tools.golden_fixtures export
        Reads the databases configured in .env and writes fixtures/golden/<version>/:
          postgres.sql   the FlowOne tables (those in the ontology): structure and rows
          neo4j.json     the whole ontology: schema, nodes and relationships
        Output is sorted, so a changed fixture shows a readable diff.

    python -m tools.golden_fixtures load --postgres-dsn ... --neo4j-uri ... --neo4j-user ... --neo4j-password ...
        Loads the fixtures into the databases named on the command line (never
        the ones in .env). Refuses a target that already holds data, so a
        development database is never overwritten by mistake.

Tables in PostgreSQL that are not in the ontology (other projects sharing the
database) are never exported. The data is synthetic (Golden Data).
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).parents[1]
VERSION = "v1"
FIXTURES = ROOT / "fixtures" / "golden"

# Node identity per label, matching the ontology's uniqueness constraints.
IDENTITY = {"Table": "key", "Column": "key", "Concept": "name", "BusinessDomain": "name"}

# pg_dump >= 17.6 adds psql-only "\restrict" lines; the fixture is plain SQL.
_PSQL_ONLY = re.compile(r"^\\(restrict|unrestrict)\b.*$\n?", re.MULTILINE)
_IF_NOT_EXISTS = re.compile(r"^(CREATE (?:CONSTRAINT|(?:RANGE |TEXT |POINT )?INDEX) `[^`]+`)")


# ================================================================== export

def export(version: str = VERSION) -> Path:
    sys.path.insert(0, str(ROOT))
    from config import settings
    from database.neo4j import Neo4jClient

    target = FIXTURES / version
    target.mkdir(parents=True, exist_ok=True)
    neo4j = Neo4jClient()
    try:
        ontology = _export_neo4j(neo4j)
    finally:
        neo4j.close()
    tables = sorted(n["properties"]["key"] for n in ontology["nodes"] if "Table" in n["labels"])
    (target / "neo4j.json").write_text(json.dumps(ontology, indent=1, sort_keys=True, ensure_ascii=False) + "\n",
                                       encoding="utf-8")
    (target / "postgres.sql").write_text(_export_postgres(settings, tables), encoding="utf-8", newline="\n")
    return target


def _export_neo4j(neo4j) -> dict:
    schema = sorted(r["s"] for r in neo4j.execute_read(
        "SHOW CONSTRAINTS YIELD createStatement AS s RETURN s"))
    schema += sorted(r["s"] for r in neo4j.execute_read(
        "SHOW INDEXES YIELD type, owningConstraint, createStatement AS s "
        "WHERE type <> 'LOOKUP' AND owningConstraint IS NULL RETURN s"))
    nodes = neo4j.execute_read(
        "MATCH (n) RETURN labels(n) AS labels, properties(n) AS properties")
    relationships = neo4j.execute_read(
        "MATCH (a)-[r]->(b) RETURN type(r) AS type, properties(r) AS properties, "
        "labels(a) AS a_labels, properties(a) AS a_props, labels(b) AS b_labels, properties(b) AS b_props")
    return {
        "schema": schema,
        "nodes": sorted(({"labels": sorted(n["labels"]), "properties": n["properties"]} for n in nodes),
                        key=lambda n: json.dumps([n["labels"], _identity(n["labels"], n["properties"])])),
        "relationships": sorted((
            {"type": r["type"], "properties": r["properties"],
             "start": _ref(r["a_labels"], r["a_props"]), "end": _ref(r["b_labels"], r["b_props"])}
            for r in relationships), key=lambda r: json.dumps([r["type"], r["start"], r["end"], r["properties"]],
                                                                sort_keys=True)),
    }


def _identity(labels, properties):
    label = next(l for l in IDENTITY if l in labels)
    return label, IDENTITY[label], properties[IDENTITY[label]]


def _ref(labels, properties) -> dict:
    label, key, value = _identity(labels, properties)
    return {"label": label, "key": key, "value": value}


def _export_postgres(settings, tables: list[str]) -> str:
    pg_dump = os.environ.get("PG_DUMP") or _find("pg_dump")
    command = [pg_dump, "--no-owner", "--no-privileges", "--inserts", "--column-inserts",
               "-h", settings.postgres_host, "-p", str(settings.postgres_port),
               "-U", settings.postgres_user, "-d", settings.postgres_db]
    for table in tables:
        command += ["-t", table]
    env = {**os.environ, "PGPASSWORD": settings.postgres_password.get_secret_value()}
    dump = subprocess.run(command, env=env, check=True, capture_output=True, text=True, encoding="utf-8").stdout
    header = ("-- FlowOne Golden Data fixture (synthetic). Generated by tools/golden_fixtures.py export;\n"
              "-- do not edit by hand. Only the tables in the ontology.\n")
    return header + _PSQL_ONLY.sub("", dump)


def _find(program: str) -> str:
    for folder in [*os.environ.get("PATH", "").split(os.pathsep),
                   *sorted(Path("C:/Program Files/PostgreSQL").glob("*/bin"), reverse=True)]:
        for name in (program, program + ".exe"):
            candidate = Path(folder) / name
            if candidate.is_file():
                return str(candidate)
    raise FileNotFoundError(f"{program} not found; set {program.upper()} to its path")


# ================================================================== load

def wait_until_ready(postgres_dsn: str, neo4j_uri: str, neo4j_user: str, neo4j_password: str,
                     seconds: float, settled_checks: int = 5) -> None:
    """
    Wait until both databases answer, and keep answering quickly. A fresh
    Neo4j container accepts a first query while still starting up (minutes
    of high CPU before it logs "Started."); connections made in that time
    stall and the application reports "Neo4j unavailable". So Neo4j must
    answer `settled_checks` times in a row, each on a new connection within
    3 seconds.
    """
    import psycopg
    from neo4j import GraphDatabase

    deadline = time.monotonic() + seconds
    streak, last_error = 0, None
    while streak < settled_checks:
        try:
            psycopg.connect(postgres_dsn, connect_timeout=3).close()
            with GraphDatabase.driver(neo4j_uri, auth=(neo4j_user, neo4j_password), connection_timeout=3,
                                      connection_acquisition_timeout=3, max_transaction_retry_time=0) as driver,                     driver.session() as session:
                session.run("RETURN 1").consume()
            streak += 1
        except Exception as exc:
            streak, last_error = 0, exc
        if time.monotonic() >= deadline:
            raise SystemExit(f"Databases not settled after {seconds:.0f} s: {type(last_error).__name__}")
        time.sleep(1)


def load(postgres_dsn: str, neo4j_uri: str, neo4j_user: str, neo4j_password: str,
         version: str = VERSION, replace: bool = False) -> dict:
    source = FIXTURES / version
    ontology = json.loads((source / "neo4j.json").read_text(encoding="utf-8"))
    rows = _load_postgres(postgres_dsn, (source / "postgres.sql").read_text(encoding="utf-8"),
                          [n["properties"]["key"] for n in ontology["nodes"] if "Table" in n["labels"]], replace)
    nodes, relationships = _load_neo4j(neo4j_uri, neo4j_user, neo4j_password, ontology, replace)
    return {"tables": len([n for n in ontology["nodes"] if "Table" in n["labels"]]), "rows": rows,
            "nodes": nodes, "relationships": relationships}


def _load_postgres(dsn: str, script: str, tables: list[str], replace: bool) -> int:
    import psycopg

    with psycopg.connect(dsn, autocommit=True) as connection:
        existing = [t for t in tables if connection.execute("SELECT to_regclass(%s)", (t,)).fetchone()[0]]
        if existing and not replace:
            raise SystemExit(f"PostgreSQL target already has {len(existing)} FlowOne table(s); use --replace "
                             "only for a disposable test database.")
        for table in existing:
            connection.execute(f"DROP TABLE {table} CASCADE")
        with connection.transaction():
            connection.execute(script)
        return sum(connection.execute(f"SELECT count(*) FROM {t}").fetchone()[0] for t in tables)


def _load_neo4j(uri: str, user: str, password: str, ontology: dict, replace: bool) -> tuple[int, int]:
    from neo4j import GraphDatabase

    with GraphDatabase.driver(uri, auth=(user, password)) as driver, driver.session() as session:
        if session.run("MATCH (n) RETURN count(n) AS c").single()["c"] and not replace:
            raise SystemExit("Neo4j target already has nodes; use --replace only for a disposable test database.")
        session.run("MATCH (n) DETACH DELETE n").consume()
        for statement in ontology["schema"]:
            # "CREATE CONSTRAINT `name` IF NOT EXISTS FOR ...": safe when reloading with --replace.
            session.run(_IF_NOT_EXISTS.sub(r"\1 IF NOT EXISTS", statement, count=1)).consume()
        for labels, group in _by_labels(ontology["nodes"]).items():
            label_text = ":".join(f"`{l}`" for l in labels)
            session.run(f"UNWIND $rows AS row CREATE (n:{label_text}) SET n = row",
                        rows=[n["properties"] for n in group]).consume()
        for (rtype, start_label, start_key, end_label, end_key), group in _by_shape(ontology["relationships"]).items():
            session.run(
                f"UNWIND $rows AS row MATCH (a:`{start_label}` {{`{start_key}`: row.a}}) "
                f"MATCH (b:`{end_label}` {{`{end_key}`: row.b}}) CREATE (a)-[r:`{rtype}`]->(b) SET r = row.p",
                rows=[{"a": r["start"]["value"], "b": r["end"]["value"], "p": r["properties"]} for r in group]).consume()
        # A freshly loaded database has no statistics yet: the planner can then
        # pick very slow plans for the ontology's path queries (seen: 81 s
        # instead of milliseconds). Refresh statistics and drop cached plans.
        session.run("CALL db.prepareForReplanning()").consume()
        nodes = session.run("MATCH (n) RETURN count(n) AS c").single()["c"]
        relationships = session.run("MATCH ()-[r]->() RETURN count(r) AS c").single()["c"]
    if nodes != len(ontology["nodes"]) or relationships != len(ontology["relationships"]):
        raise SystemExit(f"Neo4j load incomplete: {nodes} nodes, {relationships} relationships")
    return nodes, relationships


def _by_labels(nodes):
    groups: dict[tuple, list] = {}
    for n in nodes:
        groups.setdefault(tuple(n["labels"]), []).append(n)
    return groups


def _by_shape(relationships):
    groups: dict[tuple, list] = {}
    for r in relationships:
        shape = (r["type"], r["start"]["label"], r["start"]["key"], r["end"]["label"], r["end"]["key"])
        groups.setdefault(shape, []).append(r)
    return groups


# ================================================================== CLI

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("export", help="write fixtures from the databases in .env")
    loader = commands.add_parser("load", help="load fixtures into the databases named here")
    loader.add_argument("--postgres-dsn", required=True)
    loader.add_argument("--neo4j-uri", required=True)
    loader.add_argument("--neo4j-user", required=True)
    loader.add_argument("--neo4j-password", required=True)
    loader.add_argument("--replace", action="store_true", help="drop existing FlowOne data first (test databases only)")
    loader.add_argument("--wait-seconds", type=float, default=0,
                        help="first wait up to this long for both databases to answer (e.g. fresh containers)")
    for sub in commands.choices.values():
        sub.add_argument("--version", default=VERSION)
    args = parser.parse_args(argv)

    if args.command == "export":
        print(f"Exported to {export(args.version).relative_to(ROOT)}")
    else:
        if args.wait_seconds:
            wait_until_ready(args.postgres_dsn, args.neo4j_uri, args.neo4j_user, args.neo4j_password,
                             args.wait_seconds)
        result = load(args.postgres_dsn, args.neo4j_uri, args.neo4j_user, args.neo4j_password,
                      args.version, args.replace)
        print("Loaded: {tables} tables, {rows} rows; {nodes} nodes, {relationships} relationships".format(**result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
